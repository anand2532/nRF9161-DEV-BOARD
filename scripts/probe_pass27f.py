def wp(r, name, x1, y1, x2, y2, layer=B):
    path, cost = waypoint_route(r, x1, y1, x2, y2, layer, 0.18, name, xs=XS, ys=YS)
    if path is None:
        print(f"  NO {name} {layer} ({x1},{y1})->({x2},{y2})")
        return None
    print(f"  YES L={cost:.1f} n={len(path)} {path}")
    return path


def chk(r, pts, ly, name):
    ok = r.path_clear(pts, ly, 0.18, name)
    if ok:
        print("  CLEAR", pts)
        return True
    print("  BLOCK", why(r, pts, ly, 0.18, name))
    return False


