def vwhy(r, x, y, name):
    for s, d in ((0.50, 0.30), (0.45, 0.25)):
        w = r.via_why(x, y, name, size=s, drill=d)
        print(f"  via ({x:.2f},{y:.2f}) {s:.2f}/{d:.2f}", w)
        if w is None:
            return s, d
    return None


